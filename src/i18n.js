export const LANGUAGES = [['en', 'English'], ['fr', 'Français'], ['de', 'Deutsch']];
const KEY = 'submania-language';

function initial() {
  try {
    const saved = localStorage.getItem(KEY);
    if (STRINGS[saved]) return saved;
  } catch {
    // Storage can be blocked; fall back to the browser's language.
  }
  const browser = (navigator.language ?? 'en').slice(0, 2);
  return STRINGS[browser] ? browser : 'en';
}

let language = initial();
document.documentElement.lang = language;

export function getLanguage() {
  return language;
}

export function setLanguage(code) {
  if (!STRINGS[code]) return;
  language = code;
  document.documentElement.lang = code;
  try {
    localStorage.setItem(KEY, code);
  } catch {
    // Without storage, the choice lasts for this visit only.
  }
}

// `fallback` is the English for keys that keep their English elsewhere.
export function t(key, vars = {}, fallback = key) {
  const text = STRINGS[language][key] ?? STRINGS.en[key] ?? fallback;
  return text.replace(/\{(\w+)\}/g, (_, name) => vars[name] ?? '');
}

// Gives each definition a `name` and description that follow the current language.
export function localized(defs, prefix, textKey) {
  return defs.map((def) => ({
    ...def,
    get name() {
      return t(`${prefix}.${def.id}`, {}, def.name);
    },
    get [textKey]() {
      return t(`${prefix}.${def.id}.${textKey}`, {}, def[textKey]);
    },
  }));
}
